/**
 * Типизированная находка разведки: ЧТО именно найдено, а не «ещё один репозиторий».
 *
 * ЗАЧЕМ. `RepoProfile` требует `stars`, `forks` и `lastCommit` от всего подряд. У статьи звёзд
 * нет, у выпуска пакета нет форков, у поста нет ни того ни другого — и они получают нули. Ноль в
 * разведке означает ТРИ несовместимые вещи: измеренный ноль, отсутствие поля у этого вида,
 * неполученное значение. Различить нельзя, а решения принимаются по числам.
 *
 * ЧЕМ ЭТО ДОПОЛНЯЕТ ИСХОДЫ ИСТОЧНИКА. Четыре исхода (`ok`/`refused`/`timeout`/`failed`) отвечают,
 * БЫЛО ЛИ измерение. Вид находки отвечает, ЧТО измерено. Без второго первое наполовину бесполезно:
 * «источник ответил», а под ним статья с нулём звёзд, неотличимая от заброшенного репозитория.
 *
 * ЗАПРЕТ ВЫРАЖЕН ТИПОМ, А НЕ СОГЛАШЕНИЕМ — и вот его ТОЧНАЯ ГРАНИЦА, чтобы её не пришлось
 * выяснять на дефекте. Публикация не может нести звёзды при прямом присваивании, при
 * распространении и через промежуточную переменную: см. `Only` ниже. Чего система типов не ловит
 * НИ У КОГО — намеренного двухшагового расширения (`Omit`, затем обратное присваивание) и
 * `Object.assign`, возвращающего пересечение: структурная типизация без номинальных марок этого
 * не различает в принципе. Это ГРАНИЦА, а не дыра, которую забыли закрыть, и она названа здесь
 * ровно потому, что «нельзя вообще» было бы ложью — так эту строку и прочитал независимый
 * ревьюер 2026-09-03.
 */

/** Виды находок. Перечень ЗАКРЫТ: новый вид — осознанная правка здесь, а не строка в источнике. */
export const DISCOVERY_KINDS = ['repository', 'release', 'commit', 'publication', 'post'] as const;
export type DiscoveryKind = (typeof DISCOVERY_KINDS)[number];

/**
 * Значения вердикта. `unknown` — ПОЛНОПРАВНОЕ значение, а не отсутствие ответа.
 *
 * Три вердикта раздельны намеренно: свежесть, относимость к теме и новизна для нас — разные
 * суждения с разными основаниями. Один балл, в который они свёрнуты, нельзя ни оспорить, ни
 * улучшить: непонятно, какая из трёх частей ошиблась.
 */
export const VERDICT_VALUES = ['yes', 'no', 'unknown'] as const;
export type DiscoveryVerdict = (typeof VERDICT_VALUES)[number];

/**
 * Метка «значения нет» для строковых полей.
 *
 * ЧЕСТНАЯ ОГОВОРКА, чтобы её не пришлось выяснять читателю: запись `string | UNKNOWN` в системе
 * типов схлопывается в `string` — `'unknown'` и так строка, отдельного типа она не образует. То
 * есть для СТРОКОВЫХ полей это соглашение времени выполнения, закреплённое тестами и разбором на
 * входе, а не запрет компилятора. Для ЧИСЛОВЫХ полей (`number | UNKNOWN`) различие настоящее:
 * литерал `'unknown'` числом не является, и компилятор заставит его разобрать.
 */
export type Unknown = 'unknown';

/** Общее у всех видов. Ничего числового: числа принадлежат виду, а не находке вообще. */
interface DiscoveryBase {
  readonly title: string;
  readonly url: string;
  /**
   * Когда находка ПОЯВИЛАСЬ В МИРЕ. `unknown`, если источник этого не сказал — не подставляется
   * дата наблюдения. Смешение этих двух и делает ряд наблюдений несравнимым: увиденное сегодня
   * могло появиться год назад.
   */
  readonly appearedAt: string | Unknown;
  /** Когда МЫ её увидели. Всегда известно — это наше собственное время. */
  readonly observedAt: string;
  /** Кто нашёл и по какому запросу. Без этого находку нельзя перепроверить. */
  readonly provenance: { readonly source: string | Unknown; readonly query: string | Unknown };
  /**
   * Суммарного балла НЕТ, и это объявлено ЗАПРЕТОМ, а не умолчанием.
   *
   * Без явного `?: never` запрет держался бы на проверке лишних свойств — то есть только на
   * литерале в месте присваивания; тот же объект через переменную пронёс бы балл внутрь модели.
   */
  readonly score?: never;
  readonly relevanceScore?: never;
  /** Три оси, каждая отдельно. */
  readonly verdicts: {
    readonly fresh: DiscoveryVerdict;
    readonly relevant: DiscoveryVerdict;
    readonly novelToUs: DiscoveryVerdict;
  };
}

/**
 * Все поля, которые принадлежат КАКОМУ-ТО одному виду, в одном месте.
 *
 * Список здесь не для красоты: `Only` ниже вычитает из него, поэтому новое видовое поле,
 * добавленное мимо этого перечня, не получит запрета у остальных видов.
 */
interface KindFields {
  stars: number | Unknown;
  forks: number | Unknown;
  version: string;
  sha: string;
  authors: readonly string[];
  venue: string;
}

/**
 * «Ровно эти видовые поля и НИ ОДНОГО чужого».
 *
 * ПОЧЕМУ ЭТОГО НЕ ДЕЛАЕТ ОБЫЧНОЕ ОБЪЕДИНЕНИЕ. Если у публикации просто не объявить `stars`, запрет
 * будет держаться на проверке лишних свойств, а она в TypeScript срабатывает только для
 * СВЕЖЕГО литерала — записанного прямо там, где идёт присваивание. Стоит положить тот же объект в
 * переменную, и присваивание пройдёт: структурно он совместим. ИЗМЕРЕНО 2026-09-03 отдельным
 * зондом — `const x = {…, stars: 10}; const d: PublicationDiscovery = x;` компилировался.
 *
 * Поэтому чужие поля объявляются явно как `?: never`: значение под них не подобрать, и запрет
 * начинает действовать при любом способе присваивания, а не только на литерале.
 */
type Only<K extends keyof KindFields> =
  & { readonly [P in K]: KindFields[P] }
  & { readonly [P in Exclude<keyof KindFields, K>]?: never };

/** Репозиторий: единственный вид, у которого звёзды и форки осмысленны. */
export type RepositoryDiscovery = DiscoveryBase & { readonly kind: 'repository' } & Only<'stars' | 'forks'>;

/** Выпуск пакета: есть версия, звёзд нет — они у репозитория, а не у выпуска. */
export type ReleaseDiscovery = DiscoveryBase & { readonly kind: 'release' } & Only<'version'>;

/** Коммит: есть идентификатор, всё остальное — у репозитория. */
export type CommitDiscovery = DiscoveryBase & { readonly kind: 'commit' } & Only<'sha'>;

/**
 * Публикация: есть авторы. Звёзды и форки объявлены ЗАПРЕЩЁННЫМИ (`?: never`), а не просто
 * неупомянутыми — формально ключ у типа есть, но значение под него не подобрать. Разница важна
 * для читателя кода: `keyof` такой ключ покажет, и проверка `'stars' in d` больше не сужает
 * находку до репозитория. Это осознанный размен: недостижимость значения важнее отсутствия ключа.
 */
export type PublicationDiscovery = DiscoveryBase & { readonly kind: 'publication' } & Only<'authors'>;

/** Пост: есть площадка, чисел нет. */
export type PostDiscovery = DiscoveryBase & { readonly kind: 'post' } & Only<'venue'>;

/**
 * Находка. Размеченное объединение, а НЕ плоский тип с необязательными полями.
 *
 * ПОЧЕМУ НЕ `stars?: number` (вариант A отвергнут в ADR-001): вопросительный знак не различает
 * «у этого вида такого поля нет» и «не получили». Это та же неразличимость, из-за которой всё и
 * затевалось, только записанная короче.
 */
export type Discovery =
  | RepositoryDiscovery
  | ReleaseDiscovery
  | CommitDiscovery
  | PublicationDiscovery
  | PostDiscovery;

/** Минимум полей `RepoProfile`, которые преобразование читает. Локально, чтобы не тянуть весь тип. */
interface RepoProfileLike {
  readonly fullName: string;
  readonly url: string;
  readonly stars?: number;
  readonly forks?: number;
  readonly lastCommit?: string;
  readonly source?: string | undefined;
}

/** Строка считается названной, только если она непуста после обрезки пробелов. */
function named(v: string | undefined): string | Unknown {
  return typeof v === 'string' && v.trim() !== '' ? v : 'unknown';
}

/**
 * Преобразовать старый профиль в находку вида «репозиторий».
 *
 * КОНТРАКТ, дословно: поля НЕТ (`undefined`) ⇒ `unknown`; поле ЕСТЬ ⇒ переносится как есть,
 * включая ноль. Пустая строка (и строка из одних пробелов) считается отсутствием: она не
 * измерение, а незаполненное поле.
 *
 * ЧЕГО ЭТОТ КОНТРАКТ НЕ УМЕЕТ, и это надо знать до того, как опереться на число. Ноль, ПРИШЕДШИЙ
 * от источника, здесь неотличим от нуля, который источник подставил сам, не измерив: в
 * `RepoProfileLike` эти два случая записаны одинаково, и из имеющегося входа различить их нечем.
 * Вечером 2026-09-03 такие подставленные значения были убраны из источника ECC, но остальные
 * десять источников ещё не переведены на исходы (`e15bd3d7` в бэклоге) — до этого перевода
 * ложный «измеренный ноль» может прийти оттуда. Лечение — на стороне источника, не здесь:
 * преобразование, которое начнёт трактовать ноль как «не знаем», сломает СВОЙ ЖЕ контракт для
 * репозитория, у которого честно ноль звёзд.
 *
 * ВЕРДИКТЫ ПРИХОДЯТ `unknown` — старый профиль нёс один непрозрачный балл, и разложить его на три
 * оси задним числом нельзя. Честнее сказать «не знаем», чем разделить наугад.
 */
export function fromRepoProfile(p: RepoProfileLike, observedAt: string, query?: string): RepositoryDiscovery {
  return {
    kind: 'repository',
    title: p.fullName,
    url: p.url,
    appearedAt: named(p.lastCommit),
    observedAt,
    provenance: { source: named(p.source), query: named(query) },
    verdicts: { fresh: 'unknown', relevant: 'unknown', novelToUs: 'unknown' },
    stars: typeof p.stars === 'number' ? p.stars : 'unknown',
    forks: typeof p.forks === 'number' ? p.forks : 'unknown',
  };
}
